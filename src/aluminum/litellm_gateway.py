"""LiteLLM proxy configuration without importing the optional runtime."""

from __future__ import annotations

import math
import os
import shutil
import subprocess
from datetime import datetime, timezone
from pathlib import Path

import yaml
from platformdirs import user_config_dir

from aluminum.backends import REGISTRY
from aluminum.ports import GATEWAY_DEFAULT_PORT, resolve_all
from aluminum.pricing import default_rates

COST_FIELDS = ("input_cost_per_token", "output_cost_per_token")
CACHE_COST_FIELDS = ("cache_read_input_token_cost", "cache_creation_input_token_cost")
ALL_COST_FIELDS = COST_FIELDS + CACHE_COST_FIELDS


def config_path(explicit: str | None = None) -> Path:
    if explicit:
        return Path(explicit).expanduser()
    return Path(user_config_dir("aluminum")) / "litellm.yaml"


def validate_prices(prices: dict) -> dict:
    """Accept complete USD/token pairs (plus optional cache rates); absence is unknown, not free."""
    if (
        not isinstance(prices, dict)
        or not set(COST_FIELDS) <= set(prices)
        or set(prices) - set(ALL_COST_FIELDS)
    ):
        raise ValueError(
            f"Pricing must contain {', '.join(COST_FIELDS)} and may add "
            f"{', '.join(CACHE_COST_FIELDS)}"
        )
    for value in prices.values():
        if (
            isinstance(value, bool)
            or not isinstance(value, (int, float))
            or not math.isfinite(value)
            or value < 0
        ):
            raise ValueError("Prices must be finite, non-negative USD/token numbers")
    return dict(prices)


def build_config(
    provider_keys: list[str],
    models: dict[str, str],
    backend_ports: dict[str, int] | None = None,
    pricing: dict | None = None,
    otel: bool = False,
) -> dict:
    ports = resolve_all(backend_ports or {})
    if not provider_keys or any(key not in REGISTRY for key in provider_keys):
        raise ValueError("Select at least one registered provider")
    pricing = {} if pricing is None else pricing
    if not isinstance(pricing, dict) or set(pricing) - set(models):
        raise ValueError("Pricing must map selected mesh model names to USD/token prices")
    entries = []
    for alias, upstream in models.items():
        provider = alias.split(":", 1)[0]
        if provider not in provider_keys:
            raise ValueError(f"Model {alias!r} must be prefixed by a selected provider")
        params = {
            "model": f"openai/{upstream}",
            "api_base": REGISTRY[provider].base_url(ports[provider]),
            "api_key": "dummy",
        }
        if alias in pricing:
            params.update(validate_prices(pricing[alias]))
        entries.append({"model_name": alias, "litellm_params": params})
    if not entries:
        raise ValueError("Select at least one model")
    settings: dict = {"turn_off_message_logging": True}
    if otel:
        settings["callbacks"] = ["otel"]
    return {
        "model_list": entries,
        "litellm_settings": settings,
        "general_settings": {"master_key": "os.environ/LITELLM_MASTER_KEY"},
    }


def request_headers() -> dict[str, str]:
    """Use a virtual key when supplied, or the local gateway's master key."""
    key = os.environ.get("ALUM_GATEWAY_API_KEY") or os.environ.get("LITELLM_MASTER_KEY")
    return {"Authorization": "Bearer " + key} if key else {}


def write_config(config: dict, path: Path) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists():
        shutil.copy2(path, path.with_suffix(path.suffix + ".bak"))
    path.write_text(
        "# Generated by `aluminum setup --gateway litellm`.\n"
        + yaml.safe_dump(config, sort_keys=False)
    )
    return path


def launch_gateway(
    config: Path, host: str = "127.0.0.1", port: int = GATEWAY_DEFAULT_PORT
) -> subprocess.Popen:
    if host not in {"127.0.0.1", "localhost", "::1"}:
        settings = yaml.safe_load(config.read_text()) or {}
        if not isinstance(settings, dict) or not isinstance(settings.get("general_settings"), dict):
            raise ValueError("A LiteLLM general_settings.master_key is required")
        key = settings.get("general_settings", {}).get("master_key", "")
        if isinstance(key, str) and key.startswith("os.environ/"):
            key = os.environ.get(key.removeprefix("os.environ/"))
        if not isinstance(key, str) or not key.strip():
            raise ValueError("A LiteLLM master_key is required for a non-loopback bind host")
    executable = shutil.which("litellm")
    if executable is None:
        raise ValueError('LiteLLM is not installed. Install aluminum[litellm] (or aluminum[otel]).')
    return subprocess.Popen(
        [executable, "--config", str(config), "--host", host, "--port", str(port)]
    )


def cost_rows(config: dict) -> list[dict]:
    """Report configured rates only, never infer prices from a model's name."""
    if not isinstance(config, dict) or not isinstance(config.get("model_list"), list):
        raise TypeError("Expected a LiteLLM YAML config with model_list")
    rows = []
    for entry in config["model_list"]:
        if not isinstance(entry, dict) or not isinstance(entry.get("litellm_params"), dict):
            raise TypeError("Each model must have litellm_params")
        params = entry["litellm_params"]
        info = entry.get("model_info") or {}
        if not isinstance(info, dict):
            raise TypeError("model_info must be a mapping")
        prices = {}
        for field in ALL_COST_FIELDS:
            if field in info and field in params and info[field] != params[field]:
                raise ValueError(f"Conflicting {field} in model_info and litellm_params")
            if field in params or field in info:
                prices[field] = params.get(field, info.get(field))
        if prices:
            validate_prices(prices)
        rows.append({
            "model": entry.get("model_name", "?"),
            "upstream": params.get("model", "?"),
            "pricing": "configured" if prices else "unknown",
            **{field: prices.get(field) for field in ALL_COST_FIELDS},
        })
    return rows


def apply_default_pricing(config: dict) -> list[str]:
    """Fill rates for models without explicit ones; return the aliases changed.

    ALCF and Ollama are free. Argo uses GitHub Copilot's published USD/token rates.
    """
    changed = []
    for entry in config.get("model_list", []):
        params = entry.get("litellm_params", {})
        info = entry.get("model_info") or {}
        if any(f in params or f in info for f in COST_FIELDS):
            continue
        rates = default_rates(entry.get("model_name", ""))
        if rates:
            params.update(rates)
            changed.append(entry["model_name"])
    return changed


def usage_rows(logs: list[dict], since: datetime | None = None) -> list[dict]:
    """Aggregate LiteLLM spend logs per mesh model (spend is USD as computed by LiteLLM)."""
    totals: dict[str, dict] = {}
    for log in logs:
        if since is not None:
            started = datetime.fromisoformat(str(log["startTime"]).replace("Z", "+00:00"))
            if started.tzinfo is None:
                started = started.replace(tzinfo=timezone.utc)
            if started < since:
                continue
        metadata = log.get("metadata") if isinstance(log.get("metadata"), dict) else {}
        usage = metadata.get("usage_object") if isinstance(metadata.get("usage_object"), dict) else {}
        details = usage.get("prompt_tokens_details") if isinstance(
            usage.get("prompt_tokens_details"), dict
        ) else {}
        row = totals.setdefault(
            log.get("model_group") or log.get("model") or "?",
            {"requests": 0, "failed": 0, "input": 0, "output": 0, "cache_read": 0,
             "cache_write": 0, "spend": 0.0},
        )
        row["requests"] += 1
        row["failed"] += log.get("status") == "failure"
        row["input"] += log.get("prompt_tokens") or 0
        row["output"] += log.get("completion_tokens") or 0
        row["cache_read"] += details.get("cached_tokens") or 0
        row["cache_write"] += (
            details.get("cache_creation_tokens") or details.get("cache_write_tokens") or 0
        )
        row["spend"] += log.get("spend") or 0.0
    return [
        {"model": model, **row, "total_tokens": row["input"] + row["output"]}
        for model, row in sorted(totals.items())
    ]
