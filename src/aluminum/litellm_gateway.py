"""LiteLLM proxy configuration without importing the optional runtime."""

from __future__ import annotations

import math
import os
import shutil
import subprocess
from pathlib import Path

import yaml
from platformdirs import user_config_dir

from aluminum.backends import REGISTRY
from aluminum.ports import GATEWAY_DEFAULT_PORT, resolve_all

COST_FIELDS = ("input_cost_per_token", "output_cost_per_token")


def config_path(explicit: str | None = None) -> Path:
    if explicit:
        return Path(explicit).expanduser()
    return Path(user_config_dir("aluminum")) / "litellm.yaml"


def validate_prices(prices: dict) -> dict:
    """Accept complete USD/token pairs only; absence is unknown, not free."""
    if not isinstance(prices, dict) or set(prices) != set(COST_FIELDS):
        raise ValueError(f"Pricing must contain exactly {', '.join(COST_FIELDS)}")
    for value in prices.values():
        if (
            isinstance(value, bool)
            or not isinstance(value, (int, float))
            or not math.isfinite(value)
            or value < 0
        ):
            raise ValueError("Prices must be finite, non-negative USD/token numbers")
    return dict(prices)


def build_config(
    provider_keys: list[str],
    models: dict[str, str],
    backend_ports: dict[str, int] | None = None,
    pricing: dict | None = None,
    otel: bool = False,
) -> dict:
    ports = resolve_all(backend_ports or {})
    if not provider_keys or any(key not in REGISTRY for key in provider_keys):
        raise ValueError("Select at least one registered provider")
    pricing = {} if pricing is None else pricing
    if not isinstance(pricing, dict) or set(pricing) - set(models):
        raise ValueError("Pricing must map selected mesh model names to USD/token prices")
    entries = []
    for alias, upstream in models.items():
        provider = alias.split(":", 1)[0]
        if provider not in provider_keys:
            raise ValueError(f"Model {alias!r} must be prefixed by a selected provider")
        params = {
            "model": f"openai/{upstream}",
            "api_base": REGISTRY[provider].base_url(ports[provider]),
            "api_key": "dummy",
        }
        if alias in pricing:
            params.update(validate_prices(pricing[alias]))
        entries.append({"model_name": alias, "litellm_params": params})
    if not entries:
        raise ValueError("Select at least one model")
    settings: dict = {"turn_off_message_logging": True}
    if otel:
        settings["callbacks"] = ["otel"]
    return {"model_list": entries, "litellm_settings": settings}


def write_config(config: dict, path: Path) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists():
        shutil.copy2(path, path.with_suffix(path.suffix + ".bak"))
    path.write_text(
        "# Generated by `aluminum setup --gateway litellm`.\n"
        + yaml.safe_dump(config, sort_keys=False)
    )
    return path


def launch_gateway(
    config: Path, host: str = "127.0.0.1", port: int = GATEWAY_DEFAULT_PORT
) -> subprocess.Popen:
    if host not in {"127.0.0.1", "localhost", "::1"}:
        settings = yaml.safe_load(config.read_text()) or {}
        key = settings.get("general_settings", {}).get("master_key", "")
        if isinstance(key, str) and key.startswith("os.environ/"):
            key = os.environ.get(key.removeprefix("os.environ/"))
        if not key:
            raise ValueError("A LiteLLM master_key is required for a non-loopback bind host")
    executable = shutil.which("litellm")
    if executable is None:
        raise ValueError('LiteLLM is not installed. Install aluminum[litellm] (or aluminum[otel]).')
    return subprocess.Popen(
        [executable, "--config", str(config), "--host", host, "--port", str(port)]
    )


def cost_rows(config: dict) -> list[dict]:
    """Report configured rates only, never infer prices from a model's name."""
    if not isinstance(config, dict) or not isinstance(config.get("model_list"), list):
        raise TypeError("Expected a LiteLLM YAML config with model_list")
    rows = []
    for entry in config["model_list"]:
        if not isinstance(entry, dict) or not isinstance(entry.get("litellm_params"), dict):
            raise TypeError("Each model must have litellm_params")
        params = entry["litellm_params"]
        prices = {field: params[field] for field in COST_FIELDS if field in params}
        if prices:
            validate_prices(prices)
        rows.append({
            "model": entry.get("model_name", "?"),
            "upstream": params.get("model", "?"),
            "pricing": "configured" if prices else "unknown",
            **{field: prices.get(field) for field in COST_FIELDS},
        })
    return rows
